    rubric_evolution_contrast_template: Optional[str] = None
    """Template for privileged contrast answer generation."""
    rubric_evolution_decompose_template: Optional[str] = None
    """Template for dead-criterion curriculum decomposition."""
    rubric_evolution_refine_template: Optional[str] = None
