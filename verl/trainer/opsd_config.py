    rubric_generator_meta_overrides: dict[str, Any] = field(default_factory=dict)
    """Fixed meta-verifier inherits the configured Judge backend, with optional overrides."""
    rubric_generator_log_dir: Optional[str] = "tmp/rubric_generator_joint"
    rubric_generator_max_unavailable_group_fraction: float = 0.1
