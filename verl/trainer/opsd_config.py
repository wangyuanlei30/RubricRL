    rubric_gap_max_candidates_per_prompt: int = 2
    """Maximum horizontal root candidates proposed for one question per step."""
    rubric_gap_max_roots_per_prompt: int = 20
    """Maximum accepted GAP_EXPAND roots retained for one question."""
    rubric_gap_root_weight: float = 1.0
    """Absolute reward weight assigned to an accepted horizontal root."""
    rubric_evolution_interval: int = 5
    """Run contrast/proposal evolution every N training steps."""
    rubric_evolution_tau_dead: float = 0.05
    """Pass rate at or below this value marks a criterion as dead."""
    rubric_evolution_tau_sat: float = 0.95
